export const COUNTRY_MAP = new Map(COUNTRIES.map(c => [c.code, c]));

export function isValidCountryCode(code: string): boolean {
  return COUNTRY_MAP.has(code.toUpperCase());
}

export function getCountryName(code: string, lang: 'ko' | 'en' = 'ko'): string {
  const country = COUNTRY_MAP.get(code.toUpperCase());
  if (!country) return code;
  return lang === 'ko' ? country.name_ko : country.name_en;
}
